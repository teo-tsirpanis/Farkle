using System.Reflection;
using System.Reflection.Metadata;
using Microsoft.CodeAnalysis;

namespace Farkle.Analyzers.Tests;

public static class Utilities
{
    public static readonly MetadataReference? FarkleReference =
        MetadataReference.TryCreateFromRawMetadata(typeof(Builder.IGrammarSymbol).Assembly);

    // We cannot bring the source generator, because the analyzer runs before it, so we need to
    // provide a skeleton of the post-initialization-generated code manually.
    // lang=C#
    public const string EnhancedSyntaxBoilerplate = """
        // <auto-generated/>

        global using Farkle.Builder;

        using System;

        namespace Farkle.Builder;

        [AttributeUsage(AttributeTargets.All, AllowMultiple = true)]
        internal partial class UseEnhancedSyntaxAttribute : Attribute;

        internal static partial class Production
        {
            public static ProductionBuilder Create(params object[] members) => new(members);
        }

        """;

    extension(MetadataReference)
    {
        public static MetadataReference? TryCreateFromRawMetadata(Assembly assembly)
        {
            unsafe
            {
                if (!assembly.TryGetRawMetadata(out var blob, out var blobLength))
                {
                    return null;
                }
                var moduleMd = ModuleMetadata.CreateFromMetadata((IntPtr)blob, blobLength, () => GC.KeepAlive(assembly));
                var assemblyMd = AssemblyMetadata.Create(moduleMd);
                return assemblyMd.GetReference(filePath: assembly.Location, display: assembly.FullName);
            }
        }
    }
}
